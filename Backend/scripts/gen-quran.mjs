// Regenerates src/modules/learning/quran.ts from the web app's src/data/quran.js
// so the API validates ayah ranges with exactly the same reference data.
//   node scripts/gen-quran.mjs
import { writeFileSync } from 'node:fs'
import { SURAHS, juzStart } from '../../src/data/quran.js'

const counts = SURAHS.map((s) => s.ayahs)
const total = counts.reduce((a, b) => a + b, 0)
if (counts.length !== 114 || total !== 6236) throw new Error(`unexpected data: ${counts.length} surahs, ${total} ayahs`)
const starts = Array.from({ length: 30 }, (_, i) => juzStart(i + 1)).map((j) => `[${j.surah}, ${j.ayah}]`)

writeFileSync('src/modules/learning/quran.ts', `// Generated by scripts/gen-quran.mjs from the web app's src/data/quran.js. Do not edit.
// Hafs 'an 'Asim numbering: 114 surahs, 6,236 ayahs.

/** AYAH_COUNTS[n - 1] = number of ayahs in surah n. */
export const AYAH_COUNTS: readonly number[] = [${counts.join(', ')}]

/** Starting (surah, ayah) of each Juz. */
const JUZ_STARTS: readonly (readonly [number, number])[] = [${starts.join(', ')}]

export function juzOf(surah: number, ayah: number) {
  let juz = 1
  for (let i = 0; i < JUZ_STARTS.length; i++) {
    const [s, a] = JUZ_STARTS[i]!
    if (surah > s || (surah === s && ayah >= a)) juz = i + 1
    else break
  }
  return juz
}

/** Null when valid, otherwise a message for the field. */
export function ayahRangeError(surah: number, from: number, to: number) {
  const count = AYAH_COUNTS[surah - 1]
  if (!count) return 'Select a valid Surah.'
  if (from < 1) return 'Starting Ayah must be 1 or more.'
  if (to < from) return 'Ending Ayah must be the same as or after the starting Ayah.'
  if (to > count) return \`This Surah has \${count} ayahs.\`
  return null
}

export const QAIDA_LESSON_COUNT = 17
`)
console.log(`wrote quran.ts (${counts.length} surahs, ${total} ayahs)`)
